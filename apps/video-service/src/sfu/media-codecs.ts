import type { types } from 'mediasoup';

/**
 * Тип именно RouterRtpCodecCapability, а не RtpCodecCapability: в нём
 * необязателен preferredPayloadType. Номер полезной нагрузки назначает
 * сам роутер при согласовании с клиентом, и фиксировать его здесь значило
 * бы задавать значение, которое всё равно будет пересмотрено.
 */

/**
 * Кодеки, которые понимает роутер SFU.
 *
 * Набор минимальный и намеренно такой. Opus — единственный обязательный
 * аудиокодек WebRTC, поддерживается всеми браузерами. VP8 выбран как
 * видеокодек по умолчанию: он тоже обязателен по спецификации, свободен
 * от лицензионных отчислений (важно для self-hosted) и не требует от SFU
 * ничего, кроме пересылки пакетов.
 *
 * H.264 добавлен вторым: у части устройств — прежде всего у мобильных —
 * он кодируется аппаратно, и без него такой клиент греется и садит
 * батарею на программном VP8. Порядок значим: браузер выбирает первый
 * общий кодек из списка.
 *
 * SFU не перекодирует поток — он его раздаёт. Поэтому список кодеков
 * здесь не про качество, а про совместимость: чего нет в пересечении
 * возможностей всех участников, того в звонке не будет.
 */
export const MEDIA_CODECS: types.RouterRtpCodecCapability[] = [
  {
    kind: 'audio',
    mimeType: 'audio/opus',
    clockRate: 48000,
    channels: 2,
  },
  {
    kind: 'video',
    mimeType: 'video/VP8',
    clockRate: 90000,
    parameters: {
      // Целевой битрейт стартовой раскладки. Клиент подстроится сам, но
      // начальное значение определяет, насколько быстро картинка станет
      // разборчивой в первые секунды.
      'x-google-start-bitrate': 1000,
    },
  },
  {
    kind: 'video',
    mimeType: 'video/H264',
    clockRate: 90000,
    parameters: {
      'packetization-mode': 1,
      // Baseline-профиль: он есть у всех аппаратных декодеров, включая
      // старые мобильные. Более высокий профиль дал бы лучшее сжатие
      // ценой того, что часть устройств вернётся к программному
      // декодированию — то есть ровно к тому, чего мы избегаем.
      'profile-level-id': '42e01f',
      'level-asymmetry-allowed': 1,
      'x-google-start-bitrate': 1000,
    },
  },
];
