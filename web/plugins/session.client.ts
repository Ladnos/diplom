import { useAuthStore } from '~/stores/auth';

/**
 * Восстановление сессии до первой отрисовки маршрута.
 *
 * Плагин, а не middleware: он выполняется один раз при загрузке
 * приложения, тогда как middleware — на каждом переходе. Ждать
 * восстановления здесь означает, что защищённый маршрут не успеет
 * мигнуть страницей входа человеку, который на самом деле вошёл.
 */
export default defineNuxtPlugin(async () => {
  await useAuthStore().restore();
});
